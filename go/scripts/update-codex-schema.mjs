import {spawnSync} from 'node:child_process';
import {createHash, randomUUID} from 'node:crypto';
import {
  lstat,
  mkdir,
  mkdtemp,
  readFile,
  readdir,
  rename,
  rm,
  writeFile,
} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

export const TARGET_VERSION = '0.144.1';
export const GENERATION_COMMAND = 'codex app-server generate-json-schema --out <dir> --experimental';

const MANIFEST_NAME = 'manifest.json';

export function normalizeFinalNewline(value) {
  const input = Buffer.isBuffer(value) ? value : Buffer.from(value);
  let end = input.length;
  while (end > 0 && (input[end - 1] === 0x0a || input[end - 1] === 0x0d)) end -= 1;
  return Buffer.concat([input.subarray(0, end), Buffer.from('\n')]);
}

export function aggregateSchemaDigest(files) {
  const hash = createHash('sha256');
  for (const name of [...files.keys()].sort(comparePaths)) {
    hash.update(name, 'utf8');
    hash.update(Buffer.from([0]));
    hash.update(normalizeFinalNewline(files.get(name)));
    hash.update(Buffer.from([0]));
  }
  return `sha256:${hash.digest('hex')}`;
}

export function normalizeGeneratedSchema(name, value) {
  const normalized = normalizeFinalNewline(value);
  const source = normalized.toString('utf8');
  let parsed;
  try {
    parsed = JSON.parse(source);
  } catch (error) {
    throw new Error(`generated schema ${name} is not valid JSON: ${error.message}`);
  }
  if (name !== 'codex_app_server_protocol.v2.schemas.json') return normalized;
  if (!parsed.definitions || typeof parsed.definitions !== 'object' || Array.isArray(parsed.definitions)) {
    throw new Error(`generated schema ${name} has no definitions object`);
  }

  // Codex 0.144.1 emits this one combined schema from a randomized Rust map.
  // Sort only that map's entries textually so numeric lexemes and every value
  // remain byte-for-byte as emitted; all other generated bytes are untouched.
  return Buffer.from(sortRootDefinitions(source, Object.keys(parsed.definitions)), 'utf8');
}

export async function updateCodexSchema({
  schemaRoot = defaultSchemaRoot(),
  command = {file: 'codex', prefixArgs: []},
  env = process.env,
  spawn = spawnSync,
} = {}) {
  const targetDirectory = path.join(schemaRoot, TARGET_VERSION);
  await mkdir(schemaRoot, {recursive: true});

  const versionResult = run(spawn, command, ['--version'], env);
  const reportedVersion = stripSingleFinalLineEnding(versionResult.stdout);
  if (reportedVersion !== `codex-cli ${TARGET_VERSION}`) {
    throw new Error(`expected codex-cli ${TARGET_VERSION}, got ${JSON.stringify(reportedVersion)}`);
  }

  const stagingDirectory = await mkdtemp(path.join(schemaRoot, `.${TARGET_VERSION}-`));
  let stagingOwned = true;
  try {
    const generationResult = run(
      spawn,
      command,
      ['app-server', 'generate-json-schema', '--out', stagingDirectory, '--experimental'],
      env,
      {allowFailure: true},
    );
    if (generationResult.status !== 0) {
      throw new Error(`schema generation failed with status ${generationResult.status}: ${boundedDiagnostic(generationResult.stderr)}`);
    }

    const generated = await readGeneratedJSON(stagingDirectory);
    if (generated.size === 0) throw new Error('schema generation produced no JSON files');
    for (const [name, bytes] of generated) {
      await writeFile(path.join(stagingDirectory, ...name.split('/')), normalizeGeneratedSchema(name, bytes));
    }

    const normalized = await readGeneratedJSON(stagingDirectory);
    const files = [...normalized.keys()].sort(comparePaths);
    const schemaSHA256 = aggregateSchemaDigest(normalized);
    const manifest = {
      target_version: TARGET_VERSION,
      schema_sha256: schemaSHA256,
      generation_command: GENERATION_COMMAND,
      files,
      compatible: [{version: TARGET_VERSION, schema_sha256: schemaSHA256}],
    };
    await writeFile(
      path.join(stagingDirectory, MANIFEST_NAME),
      `${JSON.stringify(manifest, null, 2)}\n`,
      {encoding: 'utf8'},
    );

    await replaceDirectory(stagingDirectory, targetDirectory);
    stagingOwned = false;
    return {targetDirectory, manifest};
  } finally {
    if (stagingOwned) await rm(stagingDirectory, {recursive: true, force: true});
  }
}

function run(spawn, command, args, env, {allowFailure = false} = {}) {
  const result = spawn(command.file, [...(command.prefixArgs ?? []), ...args], {
    encoding: 'utf8',
    env,
    maxBuffer: 1 << 20,
    shell: false,
    windowsHide: true,
  });
  if (result.error) throw result.error;
  if (!allowFailure && result.status !== 0) {
    throw new Error(`command failed with status ${result.status}: ${boundedDiagnostic(result.stderr)}`);
  }
  return result;
}

async function readGeneratedJSON(root) {
  const files = new Map();
  await walk(root, '');
  return files;

  async function walk(directory, relativeDirectory) {
    const entries = await readdir(directory, {withFileTypes: true});
    entries.sort((a, b) => comparePaths(a.name, b.name));
    for (const entry of entries) {
      const relative = relativeDirectory ? `${relativeDirectory}/${entry.name}` : entry.name;
      const absolute = path.join(directory, entry.name);
      const metadata = await lstat(absolute);
      if (metadata.isSymbolicLink()) throw new Error(`generated schema contains a symbolic link: ${relative}`);
      if (metadata.isDirectory()) {
        await walk(absolute, relative);
      } else if (metadata.isFile()) {
        if (relative === MANIFEST_NAME) throw new Error('generator output unexpectedly contains manifest.json');
        if (!relative.endsWith('.json')) throw new Error(`generator output contains a non-JSON file: ${relative}`);
        files.set(relative, await readFile(absolute));
      } else {
        throw new Error(`generator output contains an unsupported entry: ${relative}`);
      }
    }
  }
}

async function replaceDirectory(stagingDirectory, targetDirectory) {
  const backupDirectory = `${targetDirectory}.backup-${randomUUID()}`;
  let backedUp = false;
  try {
    try {
      await rename(targetDirectory, backupDirectory);
      backedUp = true;
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    await rename(stagingDirectory, targetDirectory);
  } catch (error) {
    if (backedUp) {
      try {
        await rename(backupDirectory, targetDirectory);
        backedUp = false;
      } catch (restoreError) {
        throw new AggregateError([error, restoreError], 'schema replacement and rollback both failed');
      }
    }
    throw error;
  }
  if (backedUp) await rm(backupDirectory, {recursive: true, force: true});
}

function stripFinalLineEndings(value = '') {
  return value.replace(/[\r\n]+$/u, '');
}

function stripSingleFinalLineEnding(value = '') {
  if (value.endsWith('\r\n')) return value.slice(0, -2);
  if (value.endsWith('\n')) return value.slice(0, -1);
  return value;
}

function boundedDiagnostic(value = '') {
  return stripFinalLineEndings(value).slice(0, 512);
}

function comparePaths(a, b) {
  return Buffer.from(a).compare(Buffer.from(b));
}

function sortRootDefinitions(source, expectedKeys) {
  const marker = '\n  "definitions": {';
  const markerIndex = source.indexOf(marker);
  if (markerIndex < 0 || source.indexOf(marker, markerIndex + marker.length) >= 0) {
    throw new Error('combined v2 schema does not have one canonical root definitions object');
  }
  const open = markerIndex + marker.length - 1;
  const close = matchingBrace(source, open);
  const properties = splitObjectProperties(source.slice(open + 1, close));
  const observedKeys = properties.map(({key}) => key).sort(comparePaths);
  const sortedExpected = [...expectedKeys].sort(comparePaths);
  if (JSON.stringify(observedKeys) !== JSON.stringify(sortedExpected)) {
    throw new Error('combined v2 schema definitions could not be preserved during normalization');
  }
  properties.sort((a, b) => comparePaths(a.key, b.key));
  const replacement = `{\n    ${properties.map(({text}) => text).join(',\n    ')}\n  }`;
  const result = `${source.slice(0, open)}${replacement}${source.slice(close + 1)}`;
  JSON.parse(result);
  return result;
}

function matchingBrace(source, open) {
  let depth = 0;
  let inString = false;
  let escaped = false;
  for (let index = open; index < source.length; index += 1) {
    const character = source[index];
    if (inString) {
      if (escaped) escaped = false;
      else if (character === '\\') escaped = true;
      else if (character === '"') inString = false;
      continue;
    }
    if (character === '"') inString = true;
    else if (character === '{') depth += 1;
    else if (character === '}' && --depth === 0) return index;
  }
  throw new Error('combined v2 schema definitions object is unterminated');
}

function splitObjectProperties(body) {
  const properties = [];
  let index = 0;
  while (index < body.length) {
    while (/\s/u.test(body[index] ?? '')) index += 1;
    if (index >= body.length) break;
    const start = index;
    if (body[index] !== '"') throw new Error('combined v2 schema definition key is not a string');
    index = scanString(body, index);
    const key = JSON.parse(body.slice(start, index));
    while (/\s/u.test(body[index] ?? '')) index += 1;
    if (body[index] !== ':') throw new Error(`combined v2 schema definition ${key} has no value`);
    index += 1;

    let depth = 0;
    let inString = false;
    let escaped = false;
    for (; index < body.length; index += 1) {
      const character = body[index];
      if (inString) {
        if (escaped) escaped = false;
        else if (character === '\\') escaped = true;
        else if (character === '"') inString = false;
        continue;
      }
      if (character === '"') inString = true;
      else if (character === '{' || character === '[') depth += 1;
      else if (character === '}' || character === ']') depth -= 1;
      else if (character === ',' && depth === 0) break;
    }
    properties.push({key, text: body.slice(start, index).trimEnd()});
    if (body[index] === ',') index += 1;
  }
  return properties;
}

function scanString(source, start) {
  let escaped = false;
  for (let index = start + 1; index < source.length; index += 1) {
    const character = source[index];
    if (escaped) escaped = false;
    else if (character === '\\') escaped = true;
    else if (character === '"') return index + 1;
  }
  throw new Error('combined v2 schema definition key is unterminated');
}

function defaultSchemaRoot() {
  const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
  return path.resolve(scriptDirectory, '..', 'schema', 'codex');
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  updateCodexSchema()
    .then(({manifest}) => {
      process.stdout.write(`updated Codex ${manifest.target_version} schema (${manifest.schema_sha256})\n`);
    })
    .catch((error) => {
      process.stderr.write(`${error.message}\n`);
      process.exitCode = 1;
    });
}
